const cache = new Map<string, string>();

export function iconUrl(icon: string, scale = 3): string {
  const k = `${icon}@${scale}`;
  const hit = cache.get(k);
  if (hit) return hit;
  const [shape, pal] = ICONS[icon] ?? ['orb', ['#606060', '#a0a0a0', '#e0e0e0'] as Pal];
  const rows = SHAPES[shape];
  const c = document.createElement('canvas');
  c.width = 12 * scale;
  c.height = 12 * scale;
  const x = c.getContext('2d')!;
  const col: Record<string, string> = { k: '#181020', w: '#ffffff', '1': pal[0], '2': pal[1], '3': pal[2] };
  rows.forEach((row, ry) => {
    for (let rx = 0; rx < row.length; rx++) {
      const ch = row[rx];
      if (ch === '.') continue;
      x.fillStyle = col[ch] ?? '#ff00ff';
      x.fillRect(rx * scale, ry * scale, scale, scale);
    }
  });
  const url = c.toDataURL();
  cache.set(k, url);
  return url;
}

export function iconImg(icon: string, scale = 3, cls = 'ico'): HTMLImageElement {
  const img = new Image();
  img.src = iconUrl(icon, scale);
  img.className = cls;
  img.draggable = false;
  img.style.setProperty('--iw', `${(12 * scale) / 16}rem`);
  img.style.setProperty('--ih', `${(12 * scale) / 16}rem`);
  return img;
}
